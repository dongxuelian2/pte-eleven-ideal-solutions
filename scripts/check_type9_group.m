// The Mordell-Weil group used in PROOF.md, Section 5.56.
SetColumns(0);
SetSeed(1);
Q := Rationals();
search := map<PowerStructure(RngOrd) -> Integers() |
    O :-> Min(1000, MinkowskiBound(O))>;
proof := map<PowerStructure(RngOrd) -> Integers() |
    O :-> MinkowskiBound(O)>;
SetClassGroupBoundMaps(search, proof);

E := EllipticCurve([Q | 0, 1, 1, 295, 1109]);
G := E![31, 202, 1];
lo, hi := RankBounds(E);
assert lo eq 1 and hi eq 1;
assert #TorsionSubgroup(E) eq 1;
gens, rank_proved, full_group := Generators(E);
assert rank_proved and full_group;
assert #gens eq 1 and (gens[1] eq G or gens[1] eq -G);
print "E(Q) is generated by (31,202) and has trivial torsion.";

// Smooth ordered-root curve used in the genus-four corollary.
P3<r,s,b,w> := ProjectiveSpace(Q, 3);
c2 := -352*b-688*w;
c1 := 432*b^2+1840*b*w+2124*w^2;
c0 := 216*b^3-492*b^2*w-1974*b*w^2-2025*w^3;
f := 64*r^3+c2*r^2+c1*r+c0;
q := 64*(r^2+r*s+s^2)+c2*(r+s)+c1;
Y := Curve(P3, [q,f]);
assert IsNonsingular(Y) and IsAbsolutelyIrreducible(Y) and Genus(Y) eq 4;
print "The ordered-root curve is smooth, geometrically integral and of genus four.";
